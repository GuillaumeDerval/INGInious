#!/usr/bin/env node
/**
 * Generates docs/features/INDEX.md from the feature files (docs/features/<area>/*.md):
 * one table per area with ID, title, actors and dependencies, plus the list of
 * integration tests (e2e/**) referencing each ID, so that parity coverage can
 * be checked at a glance. Run from the frontend folder: `node tools/feature-index.mjs`.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const featuresDir = path.join(root, 'docs/features');
const e2eDir = path.join(root, 'e2e');
const AREAS = {
	core: 'Cross-cutting',
	auth: 'Authentication & accounts',
	nav: 'Student navigation',
	task: 'Task page & submissions',
	'course-admin': 'Course administration',
	'course-students': 'People & results administration',
	site: 'Site administration, API, plugins',
	lti: 'LTI'
};

/** Lists files recursively. */
const walk = (dir) =>
	fs.existsSync(dir)
		? fs
				.readdirSync(dir, { withFileTypes: true })
				.flatMap((d) => (d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]))
		: [];

// Integration test titles referencing feature ids.
const tests = {};
for (const file of walk(e2eDir).filter((f) => f.endsWith('.e2e.ts'))) {
	// A title may start with several ids: "NAV-04 CADM-01 a superadmin creates...".
	for (const m of fs.readFileSync(file, 'utf8').matchAll(/test(?:\.\w+)?\(\s*['"`]((?:[A-Z]+-\d+[ /,]*)+)/g)) {
		for (const id of m[1].match(/[A-Z]+-\d+/g))
			(tests[id] ??= new Set()).add(path.relative(path.join(root, 'app'), file));
	}
}

let out = '# Feature index\n\nGenerated by `tools/feature-index.mjs` — do not edit by hand.\n\n';
let total = 0;
let tested = 0;
for (const [area, label] of Object.entries(AREAS)) {
	const files = walk(path.join(featuresDir, area))
		.filter((f) => f.endsWith('.md'))
		.sort();
	if (!files.length) continue;
	out += `## ${label} (\`${area}\`)\n\n| ID | Feature | Actors | Depends on | Integration tests |\n|---|---|---|---|---|\n`;
	for (const file of files) {
		const text = fs.readFileSync(file, 'utf8');
		const id = /\*\*ID\*\*:\s*([A-Z]+-\d+)/.exec(text)?.[1] ?? '?';
		const title = text.split('\n')[0].replace(/^#\s*/, '');
		const field = (name) =>
			(new RegExp(`\\*\\*${name}\\*\\*:\\s*(.*)`).exec(text)?.[1] ?? '').replace(/\|/g, '\\|').slice(0, 120);
		const t = tests[id] ? [...tests[id]].length : 0;
		total++;
		if (t) tested++;
		out += `| ${id} | [${title}](${path.relative(featuresDir, file)}) | ${field('Actors')} | ${field('Depends on')} | ${t ? '✅ ' + t : '—'} |\n`;
	}
	out += '\n';
}
out = out.replace('\n\n', `\n\n**${total} features**, ${tested} with at least one integration test.\n\n`);
fs.writeFileSync(path.join(featuresDir, 'INDEX.md'), out);
console.log(`${total} features, ${tested} tested`);
